        public void loadStaff(int staffId, String name, String email, String dateAdded) {
        lblName.setText(name);
        lblEmail.setText(email);
        lblAdded.setText(dateAdded);
        jLabel3.setText("Staff ID no.: " + staffId);

        try {
            String[] p = new userDao().getStaffProfile(staffId);   // {team, specialization, availability, contact no}
            if (p != null) {
                jLabel2.setText(p[0]);
                lblWork.setText(p[1]);
                lblAvail.setText(p[2]);
                lblNo.setText(p[3] == null || p[3].isEmpty() ? "-" : p[3]);
            }

            java.util.Map<String, Integer> c = new RequestDAO().getTaskCounts(staffId);
            int pending = c.getOrDefault("Assigned", 0);
            int inProgress = c.getOrDefault("In Progress", 0);
            int completed = c.getOrDefault("Completed", 0);

            lblCateg19.setText(String.valueOf(pending + inProgress + completed));   // total tasks
            lblCateg20.setText(String.valueOf(pending));
            lblCateg21.setText(String.valueOf(inProgress));
            lblCateg22.setText(String.valueOf(completed));

        } catch (java.sql.SQLException e) {
            Helper.showError(this, e);
        }
    }
        
