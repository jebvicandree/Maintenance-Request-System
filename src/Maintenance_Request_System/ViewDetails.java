    public ViewDetails(java.awt.Frame parent, boolean modal, int requestId) {
        this(parent, modal);
        this.requestId = requestId;

        buttons1.addActionListener(e -> cancelRequest());   // CANCEL REQUEST
        whiteBtn1.addActionListener(e -> dispose());        // BACK
        viewPhoto.addActionListener(e -> showPhoto());      // View photo

        loadDetails();
    }

    private void loadDetails() {
        try {
            RequestDAO.RequestInfo r = new RequestDAO().getRequest(requestId);
            if (r == null) {
                return;
            }

            lblRequestID.setText("REQ ID: " + r.id);
            lblName.setText(r.requesterName);
            jLabel2.setText(r.requesterRole + " - " + r.department);
            jLabel3.setText("Submitted: " + r.dateSubmitted);
            lblIssue.setText(r.issue);
            lblLoc.setText(r.location);
            lblCateg.setText(r.category);
            lblPrior.setText(r.priority == null ? "Not set" : r.priority);
            desc.setText(r.description);

            photoPath = r.photoPath;
            if (photoPath != null) {
                attachLbl.setIcon(Helper.scaledIcon(photoPath, 106, 71));
            }

            // A student can only cancel while the request is still Pending
            buttons1.setEnabled("Pending".equals(r.status));

        } catch (java.sql.SQLException e) {
            Helper.showError(this, e);
        }
    }

    private void cancelRequest() {
        int answer = javax.swing.JOptionPane.showConfirmDialog(this,
                "Cancel this request?", "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
        if (answer != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {
            if (new RequestDAO().cancelRequest(requestId)) {
                javax.swing.JOptionPane.showMessageDialog(this, "Request cancelled.");
                dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Only pending requests can be cancelled.");
            }
        } catch (java.sql.SQLException e) {
            Helper.showError(this, e);
        }
    }

    private void showPhoto() {
        javax.swing.ImageIcon icon = Helper.scaledIcon(photoPath, 500, 400);
        if (icon == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "No photo attached.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, new javax.swing.JLabel(icon),
                    "Photo", javax.swing.JOptionPane.PLAIN_MESSAGE);
        }
    }

