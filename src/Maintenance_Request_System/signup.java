    private void buttons1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttons1ActionPerformed
      
        //STUDENT INFORMATION
        String firstName = roundedSearchField1.getText().trim();
        String lastName = roundedSearchField2.getText().trim();
        String middleName = roundedSearchField3.getText().trim();
        String departmentName = roundedComboBox1.getSelectedItem().toString().trim();
        String yearLevel = roundedComboBox2.getSelectedItem().toString().trim();
        String section = roundedSearchField7.getText().trim();
        //ACCOUNT INFORMATION
        String email = roundedSearchField8.getText().trim();
        String password = roundedPasswordField1.getText().trim();
        String confirmPassword = roundedPasswordField2.getText().trim();
        
        
        //VALIDATIONS
        if (firstName.isEmpty() 
            && lastName.isEmpty() 
            && middleName.isEmpty() 
            && roundedComboBox1.getSelectedIndex() <= 0 
            && roundedComboBox2.getSelectedIndex() <= 0
            && section.isEmpty() 
            && email.isEmpty()
            && password.isEmpty() 
            && confirmPassword.isEmpty())
             {

            JOptionPane.showMessageDialog(this,
                    "Please fill in all fields.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (roundedComboBox1.getSelectedIndex() == 0) {

            JOptionPane.showMessageDialog(this,
                    "Please select your department.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (roundedComboBox2.getSelectedIndex() == 0) {

            JOptionPane.showMessageDialog(this,
                    "Please select your year level.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (firstName.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please enter your first name.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (lastName.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please enter your last name.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (middleName.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please enter your middle name.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (roundedComboBox1.getSelectedIndex() <= 0) {

            JOptionPane.showMessageDialog(this,
                    "Please select which department you belong.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (roundedComboBox2.getSelectedIndex() <= 0) {

            JOptionPane.showMessageDialog(this,
                    "Please select your year level.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (section.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please enter your section.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (email.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please enter your phinmaed account.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (password.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please enter your password.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (confirmPassword.isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Please confirm your password.",
                    "Sign Up",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        //&& !email.matches("^[a-z]+\\.[a-z]+\\.coc@phinmaed\\.com$"))
        if (!email.matches("^[a-z]+\\.[a-z]+\\.coc@phinmaed\\.com$")) {

            JOptionPane.showMessageDialog(this,
                    "Please enter your phinmaed account.",
                    "Invalid Email Address",
                    JOptionPane.WARNING_MESSAGE);
            return;
        } 
    try {
    userDao dao = new userDao();

    boolean success = dao.signup(
            firstName, lastName, middleName,
            departmentName, yearLevel, section,
            email, password
    );

    if (!success) {
        JOptionPane.showMessageDialog(this,
                "This email is already registered.",
                "Email Already Exists",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    JOptionPane.showMessageDialog(this,
            "Account created successfully! Please log in.",
            "Sign Up Successful",
            JOptionPane.INFORMATION_MESSAGE);

    login loginform = new login();
    loginform.setLocationRelativeTo(null);
    loginform.setVisible(true);
    this.dispose();

} catch (SQLException e) {
    JOptionPane.showMessageDialog(this,
            "Error creating account: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
    e.printStackTrace();
}
    }//GEN-LAST:event_buttons1ActionPerformed

