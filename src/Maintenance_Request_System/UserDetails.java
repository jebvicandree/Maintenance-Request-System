    public void loadStudent(int userId, String name, String email, String dateRegistered) {
        lblName.setText(name);
        lblEmail.setText(email);
        lblReg.setText(dateRegistered);
        jLabel3.setText("Student ID no.: " + userId);
        lblNo.setText("-");

        try {
            String[] p = new userDao().getStudentProfile(userId);   // {department, year level, section}
            if (p != null) {
                jLabel2.setText(p[0]);
                lbCourse.setText(p[0]);
                lblgryr.setText(p[1]);
                lblsect.setText(p[2]);
            }

            java.util.Map<String, Integer> c = new RequestDAO().getRequestCounts(userId);
            lblrq.setText(String.valueOf(RequestDAO.total(c)));
            lblpend.setText(String.valueOf(c.getOrDefault("Pending", 0)));
            lblPro.setText(String.valueOf(c.getOrDefault("In Progress", 0)));
            lblComp.setText(String.valueOf(c.getOrDefault("Completed", 0)));

        } catch (java.sql.SQLException e) {
            Helper.showError(this, e);
        }
    }
