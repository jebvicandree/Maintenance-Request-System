    private int requestId;
    private int staffId;
    private String photoPath;

    public AssignedTasks(java.awt.Frame parent, boolean modal, int requestId, int staffId) {
        this(parent, modal);
        this.requestId = requestId;
        this.staffId = staffId;

        update.addActionListener(e -> saveStatus());
        viewPhoto.addActionListener(e -> showPhoto());

        loadDetails();
    }

    private void loadDetails() {
        try {
            RequestDAO dao = new RequestDAO();
            RequestDAO.RequestInfo r = dao.getRequest(requestId);
            String[] task = dao.getTaskInfo(requestId, staffId);   // {status, date assigned, target date}
            if (r == null || task == null) {
                return;
            }

            jLabel8.setText("REQ ID: " + r.id);
            jLabel1.setText(r.requesterName);
            jLabel2.setText(r.requesterRole + " - " + r.department);
            jLabel3.setText("Submitted: " + r.dateSubmitted);
            lblIssue.setText(r.issue);
            lblLoc.setText(r.location);
            lblCateg.setText(r.category);
            lblPrior.setText(r.priority == null ? "Not set" : r.priority);
            descriptxt.setText(r.description);
            dateAssign.setText(task[1]);
            targetComp.setText(task[2]);

            photoPath = r.photoPath;
            if (photoPath != null) {
                attachLbl.setIcon(Helper.scaledIcon(photoPath, 106, 83));
            }

            // Task already accepted before? Go straight to the progress controls.
            if (!task[0].equals("Assigned")) {
                showProgressControls();
                statusCmb.setSelectedItem(task[0]);
                update.setEnabled(!task[0].equals("Completed"));
            }

        } catch (java.sql.SQLException e) {
            Helper.showError(this, e);
        }
    }

    // Hides ACCEPT/CANCEL and shows the progress dropdown + UPDATE
    private void showProgressControls() {
        cancel1.setVisible(false);
        accept.setVisible(false);

        statusCmb.setVisible(true);
        cancel2.setVisible(true);
        update.setVisible(true);
        lblword.setVisible(true);
    }

    private void saveStatus() {
        String newStatus = statusCmb.getSelectedItem().toString();

        try {
            new RequestDAO().updateTaskStatus(requestId, staffId, newStatus);
            javax.swing.JOptionPane.showMessageDialog(this, "Task updated to: " + newStatus);
            dispose();
        } catch (java.sql.SQLException e) {
            Helper.showError(this, e);
        }
    }

    private void showPhoto() {
        javax.swing.ImageIcon icon = Helper.scaledIcon(photoPath, 500, 400);
        if (icon == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "No photo attached.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, new javax.swing.JLabel(icon),
                    "Photo", javax.swing.JOptionPane.PLAIN_MESSAGE);
        }
    }
        private void addItems() {
    statusCmb.setModel(new javax.swing.DefaultComboBoxModel<>(
        new String[] { "In Progress", "Completed" }));
        }
        
